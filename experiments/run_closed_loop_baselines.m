function runs=run_closed_loop_baselines(cfg)
%RUN_CLOSED_LOOP_BASELINES Experiments 1-3 on shared Plant conditions.
if nargin<1, cfg=closed_loop_config(); end
s=closed_loop_scenarios(cfg); c=closed_loop_controllers();
spec={ ...
    'E1_C1_nominal',1,1; ...
    'E2_C1_mismatch',2,1; ...
    'E2_C3_mismatch',2,3; ...
    'E3_C1_disturbance',3,1; ...
    'E3_C2_disturbance',3,2; ...
    'E3_C3_disturbance',3,3};
runs=cell(size(spec,1),1);
for k=1:size(spec,1)
    runs{k}=simulate_closed_loop_case(s(spec{k,2}),c(spec{k,3}),cfg);
    runs{k}.run_name=spec{k,1};
end
end
